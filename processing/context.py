"""Build compact LLM contexts from long sections (a 10-K is far larger than an 8k context)."""

from __future__ import annotations

import re
from datetime import date

FIN_KEYWORDS = re.compile(
    r"(?im)^[ \t]*(total net sales|total (?:net )?revenues?|net revenues?|net sales|net income|"
    r"net earnings|net cash [^\n]{0,40}operating activities|cash generated by operating activities)"
)
UNIT_CAPTION = re.compile(r"(?i)\(?in (millions|thousands|billions)")
LEADER_KEYWORDS = re.compile(
    r"(?i)chief executive officer|chief financial officer|board of directors"
)


def header(company: str | None, form_type: str, period_end: date | None, item: str) -> str:
    return (
        f"Company: {company or 'unknown'}\nForm: {form_type}\n"
        f"Fiscal period end: {period_end.isoformat() if period_end else 'unknown'}\n"
        f"Section: Item {item}\n---\n"
    )


def keyword_windows(
    text: str, pattern: re.Pattern[str], before: int, after: int, max_chars: int
) -> str:
    spans: list[list[int]] = []
    for m in pattern.finditer(text):
        lo, hi = max(0, m.start() - before), min(len(text), m.end() + after)
        lo = text.rfind("\n", 0, lo) + 1
        if spans and lo <= spans[-1][1]:
            spans[-1][1] = max(spans[-1][1], hi)
        else:
            spans.append([lo, hi])
    out, total = [], 0
    for lo, hi in spans:
        chunk = text[lo:hi]
        if total + len(chunk) > max_chars:
            chunk = chunk[: max_chars - total]
        out.append(chunk)
        total += len(chunk)
        if total >= max_chars:
            break
    return "\n...\n".join(out)


def financial_context(sections: dict[str, str], max_chars: int = 18000) -> str:
    parts = []
    budget = max_chars
    for item in ("8", "7"):
        text = sections.get(item)
        if not text or budget <= 0:
            continue
        caption = UNIT_CAPTION.search(text)
        cap = f"[{caption.group(0)}]\n" if caption else ""
        windows = keyword_windows(text, FIN_KEYWORDS, 200, 500, budget)
        if windows:
            chunk = f"## Item {item}\n{cap}{windows}"
            parts.append(chunk)
            budget -= len(chunk)
    return "\n\n".join(parts)


def headline_compress(text: str, max_chars: int = 18000) -> str:
    """Keep the first sentence of each paragraph: risk factor headlines survive, bodies go."""
    out, total = [], 0
    for para in re.split(r"\n\s*\n", text):
        para = para.strip()
        if len(para) < 40:
            continue
        first = re.split(r"(?<=[.!?])\s+(?=[A-Z])", para, maxsplit=1)[0][:400]
        if total + len(first) > max_chars:
            break
        out.append(first)
        total += len(first) + 1
    return "\n".join(out)


def risk_context(sections: dict[str, str], max_chars: int = 18000) -> str:
    return headline_compress(sections.get("1A", ""), max_chars)


def leadership_context(sections: dict[str, str], max_chars: int = 8000) -> str:
    text = "\n".join(sections.get(i, "") for i in ("1", "10"))
    return keyword_windows(text, LEADER_KEYWORDS, 300, 300, max_chars)


SOURCE_ITEMS: dict[str, tuple[str, ...]] = {
    "FinancialHighlights": ("8", "7"),
    "RiskFactors": ("1A",),
    "Leadership": ("1",),
}

BUILDERS = {
    "FinancialHighlights": financial_context,
    "RiskFactors": risk_context,
    "Leadership": leadership_context,
}
