def classify_risk(text: str) -> str:
    low = f" {text.lower()} "
    best, best_hits = "other", 0
    for cat, words in RISK_KEYWORDS.items():
        hits = sum(low.count(w) for w in words)
        if hits > best_hits:
            best, best_hits = cat, hits
    return best


def _parse_number(raw: str) -> float:
    neg = raw.strip().startswith("(") or raw.strip().startswith("-")
    value = float(re.sub(r"[^\d.]", "", raw) or 0)
    return -value if neg else value


def find_figure(text: str, field: str) -> tuple[float, str] | None:
    for label in _FIN_LABELS[field]:
        for m in re.finditer(rf"(?im)^[ \t]*{label}\b[^\n\d(]{{0,40}}", text):
            tail = text[m.end() : m.end() + 120]
            num = re.match(rf"[ \t$]*{_NUM}", tail)
            if not num:
                continue
            raw = num.group(0)
            digits = re.sub(r"[^\d]", "", raw)
            if len(digits) == 4 and digits.startswith(("19", "20")) and "," not in raw:
                continue
            value = _parse_number(raw)
            snippet = text[m.start() : m.end() + num.end()].strip().replace("\t", " ")
            return value, re.sub(r"\s+", " ", snippet)[:400]
    return None


def detect_units(text: str) -> str:
    low = text.lower()
    for unit in ("millions", "thousands", "billions"):
        if f"in {unit}" in low:
            return unit
    return "millions"


class RulesProvider:
    """Deterministic, offline extractor implementing the LLMProvider interface."""

    def __init__(self, model: str = RULES_MODEL) -> None:
        self.model = model

    def complete_json(
        self, system: str, messages: list[dict[str, str]], schema: dict[str, Any]
    ) -> LLMResult:
        t0 = time.perf_counter()
        text = messages[0]["content"]
        title = schema.get("title", "")
        handler = {
            "FinancialHighlights": self._financials,
            "RiskFactors": self._risks,
            "Leadership": self._leadership,
            "Invoice": self._invoice,
        }[title]
        out = handler(text)
        return LLMResult(json.dumps(out), int((time.perf_counter() - t0) * 1000), self.model)

    @staticmethod
    def _header(text: str, key: str) -> str | None:
        m = re.search(rf"(?im)^{key}:\s*(.+)$", text)
        return m.group(1).strip() if m else None

    def _financials(self, text: str) -> dict[str, Any]:
        period = self._header(text, "Fiscal period end") or ""
        year = int(period[:4]) if period[:4].isdigit() else 2000
        out: dict[str, Any] = {"fiscal_year": year, "currency": "USD", "units": detect_units(text)}
        found = 0
        for field in ("revenue", "net_income", "operating_cash_flow"):
            hit = find_figure(text, field)
            out[field] = hit[0] if hit else None
            out[f"{field}_snippet"] = hit[1] if hit else None
            found += bool(hit)
        out["self_confidence"] = round(0.3 + 0.2 * found, 2)
        return out

    def _risks(self, text: str) -> dict[str, Any]:
        risks: list[dict[str, str]] = []
        seen: set[str] = set()
        for line in text.split("\n---\n", 1)[-1].split("\n"):
            line = line.strip()
            if not (60 <= len(line) <= 400) or line.lower().startswith(
                ("item ", "filing", "company", "the following", "this section", "investors should",
                 "in addition to", "you should", "the risks described", "these risks")
            ):  # fmt: skip
                continue
            category = classify_risk(line)
            if category in seen and len(risks) >= 6:
                continue
            seen.add(category)
            summary = re.split(r"(?<=[.;])\s", line)[0][:300]
            risks.append({"category": category, "summary": summary, "snippet": line[:400]})
            if len(risks) >= 12:
                break
        return {"risks": risks, "self_confidence": 0.5 if risks else 0.1}

    def _leadership(self, text: str) -> dict[str, Any]:
        def person(title: str) -> tuple[str | None, str | None]:
            m = re.search(
                rf"([A-Z][a-z]+(?: [A-Z]\.)?(?: [A-Z][a-zA-Z'\-]+){{1,2}})[^\n]{{0,40}}{title}",
                text,
            )
            return (m.group(1), m.group(0)[:400]) if m else (None, None)

        ceo, ceo_snip = person("Chief Executive Officer")
        cfo, cfo_snip = person("Chief Financial Officer")
        return {
            "ceo": ceo,
            "ceo_snippet": ceo_snip,
            "cfo": cfo,
            "cfo_snippet": cfo_snip,
            "board_size": None,
            "self_confidence": 0.4,
        }

    def _invoice(self, text: str) -> dict[str, Any]:
        def grab(label: str) -> str | None:
            m = re.search(rf"(?im)^{label}\s*[:#]?\s*(.+)$", text)
            return m.group(1).strip() if m else None

        def money(label: str) -> float:
            v = grab(label)
            return _parse_number(v.split()[0]) if v else 0.0

        items = []
        for m in re.finditer(
            r"(?m)^(.+?)\s+(\d+(?:\.\d+)?)\s+x\s+([\d,]+\.\d{2})\s+=\s+([\d,]+\.\d{2})$", text
        ):
            items.append(
                {
                    "description": m.group(1).strip(),
                    "quantity": float(m.group(2)),
                    "unit_price": _parse_number(m.group(3)),
                    "amount": _parse_number(m.group(4)),
                }
            )
        rate_raw = grab("VAT rate") or "0%"
        return {
            "vendor": grab("Vendor") or "unknown",
            "invoice_number": grab("Invoice number") or "unknown",
            "invoice_date": grab("Invoice date") or "2000-01-01",
            "due_date": grab("Due date"),
            "currency": (grab("Currency") or "EUR")[:3],
            "line_items": items,
            "subtotal": money("Subtotal"),
            "vat_rate": float(rate_raw.strip("%")) / 100,
            "vat_amount": money("VAT amount"),
            "total": money("Total"),
            "self_confidence": 0.6,
        }


class HashingEmbedder:
    """Deterministic bag-of-words hashing embedder (offline stand-in for nomic-embed-text)."""

    def __init__(self, dim: int | None = None) -> None:
        self.dim = dim or get_settings().embed_dim
        self.model = f"hashing-{self.dim}"

    def embed(self, texts: list[str]) -> list[list[float]]:
        out = []
        for text in texts:
            vec = [0.0] * self.dim
            for tok in re.findall(r"[a-z][a-z0-9]{2,}", text.lower()):
                h = int.from_bytes(hashlib.blake2b(tok.encode(), digest_size=8).digest(), "big")
                vec[h % self.dim] += 1.0 if (h >> 32) & 1 else -1.0
            norm = math.sqrt(sum(v * v for v in vec)) or 1.0
            out.append([v / norm for v in vec])
        return out


def get_provider(model: str | None = None) -> LLMProvider:
    s = get_settings()
    if s.llm_provider == "fake" or model == RULES_MODEL:
        return RulesProvider()
    return OllamaProvider(model)


@lru_cache
def get_embedder() -> Embedder:
    if get_settings().llm_provider == "fake":
        return HashingEmbedder()
    return OllamaEmbedder()
